/**
 * Data access with a localStorage draft layer over the committed JSON files.
 *
 * There is no server, so the JSON in data/ is the shared source of truth and
 * edits made in the browser live in localStorage until someone exports them and
 * commits the result. Every read goes through here so that a page never has to
 * care whether it is looking at committed data or a local draft.
 */

const DRAFT_PREFIX = 'tmb:draft:';
const PREF_PREFIX = 'tmb:pref:';

export const FILES = {
  settings: 'data/settings.json',
  itinerary: 'data/itinerary.json',
  waypoints: 'data/waypoints.json',
  people: 'data/people.json',
  stays: 'data/stays.json',
  expenses: 'data/expenses.json',
  rates: 'data/rates.json',
};

// Generated by the pipeline and never edited in the browser, so these are fetched
// directly without a draft layer. Photos live here rather than in FILES because
// tools/fetch_photos.py owns the file, and because the attribution in it is a
// licence condition rather than something anyone should be editing by hand.
//
// History is here for a different reason: it is researched prose with citations,
// and a draft layer would serialise the whole of it into localStorage on every
// unrelated waypoint edit.
const READ_ONLY = {
  anchors: 'data/route/anchors.json',
  legIndex: 'data/route/legs/index.json',
  loop: 'data/route/tmb-loop-oriented.geojson',
  photos: 'data/photos.json',
  history: 'data/history.json',
};

const committed = new Map();
const drafts = new Map();
const readOnlyCache = new Map();
const legCache = new Map();
const listeners = new Set();

let ready = false;

/* ------------------------------------------------------------------ */
/* loading                                                             */
/* ------------------------------------------------------------------ */

async function fetchJson(path) {
  const response = await fetch(path, { cache: 'no-cache' });
  if (!response.ok) {
    throw new Error(`Could not load ${path} (HTTP ${response.status})`);
  }
  return response.json();
}

function readDraft(name) {
  try {
    const raw = localStorage.getItem(DRAFT_PREFIX + name);
    return raw ? JSON.parse(raw) : null;
  } catch (error) {
    console.warn(`Ignoring unreadable draft for ${name}`, error);
    return null;
  }
}

/** Load every editable file plus the route manifests. Call once per page. */
export async function init(names = Object.keys(FILES)) {
  await Promise.all(
    names.map(async (name) => {
      committed.set(name, await fetchJson(FILES[name]));
      const draft = readDraft(name);
      if (draft) drafts.set(name, draft);
    })
  );
  ready = true;
  notify();
}

export function isReady() {
  return ready;
}

/** Fetch and memoise one of the generated route files. */
export async function loadRouteFile(key) {
  if (!readOnlyCache.has(key)) {
    readOnlyCache.set(key, await fetchJson(READ_ONLY[key]));
  }
  return readOnlyCache.get(key);
}

/** Fetch one day/variant leg, e.g. loadLeg('day-03', 'classic'). */
export async function loadLeg(dayId, variant) {
  const key = `${dayId}-${variant}`;
  if (!legCache.has(key)) {
    legCache.set(key, await fetchJson(`data/route/legs/${key}.json`));
  }
  return legCache.get(key);
}

/* ------------------------------------------------------------------ */
/* reading and writing                                                 */
/* ------------------------------------------------------------------ */

/** Current value of a file: the draft if one exists, otherwise committed. */
export function get(name) {
  if (drafts.has(name)) return drafts.get(name);
  const value = committed.get(name);
  if (value === undefined) {
    throw new Error(`store.get('${name}') before init() loaded it`);
  }
  return value;
}

/**
 * Mutate a file through a callback. The callback receives a deep clone, so
 * accidental mutation of committed data is impossible, and the result is
 * persisted as a draft.
 */
export function update(name, mutator) {
  const next = structuredClone(get(name));
  const returned = mutator(next);
  const value = returned === undefined ? next : returned;

  if (JSON.stringify(value) === JSON.stringify(committed.get(name))) {
    // Edited back to the committed state — drop the draft entirely rather than
    // leaving a no-op change showing as unsaved.
    drafts.delete(name);
    localStorage.removeItem(DRAFT_PREFIX + name);
  } else {
    drafts.set(name, value);
    try {
      localStorage.setItem(DRAFT_PREFIX + name, JSON.stringify(value));
    } catch (error) {
      console.error('Could not save draft — localStorage may be full', error);
    }
  }
  notify();
  return value;
}

export function isDirty(name) {
  return name ? drafts.has(name) : drafts.size > 0;
}

export function dirtyFiles() {
  return [...drafts.keys()];
}

/** Discard local edits for one file, or all files when name is omitted. */
export function revert(name) {
  const names = name ? [name] : [...drafts.keys()];
  names.forEach((key) => {
    drafts.delete(key);
    localStorage.removeItem(DRAFT_PREFIX + key);
  });
  notify();
}

/* ------------------------------------------------------------------ */
/* export and import                                                   */
/* ------------------------------------------------------------------ */

/** Exact file content to paste into the GitHub web editor. */
export function exportJson(name) {
  return `${JSON.stringify(get(name), null, 2)}\n`;
}

export function fileNameFor(name) {
  return FILES[name].split('/').pop();
}

export function pathFor(name) {
  return FILES[name];
}

export function download(name) {
  const blob = new Blob([exportJson(name)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileNameFor(name);
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

export async function copyToClipboard(name) {
  const text = exportJson(name);
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Clipboard API needs a secure context; fall back to a hidden textarea so
    // this still works when the site is opened over plain http on a phone.
    const field = document.createElement('textarea');
    field.value = text;
    field.setAttribute('readonly', '');
    field.style.position = 'fixed';
    field.style.opacity = '0';
    document.body.appendChild(field);
    field.select();
    const ok = document.execCommand('copy');
    field.remove();
    return ok;
  }
}

/** Load a teammate's exported file as the local draft. */
export function importJson(name, text) {
  const parsed = JSON.parse(text);
  return update(name, () => parsed);
}

/* ------------------------------------------------------------------ */
/* preferences (device-local, never exported)                          */
/* ------------------------------------------------------------------ */

export function pref(key, fallback = null) {
  const raw = localStorage.getItem(PREF_PREFIX + key);
  if (raw === null) return fallback;
  try {
    return JSON.parse(raw);
  } catch {
    return fallback;
  }
}

export function setPref(key, value) {
  localStorage.setItem(PREF_PREFIX + key, JSON.stringify(value));
  notify();
}

/* ------------------------------------------------------------------ */
/* change notification                                                 */
/* ------------------------------------------------------------------ */

export function subscribe(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function notify() {
  listeners.forEach((listener) => {
    try {
      listener();
    } catch (error) {
      console.error('Store listener failed', error);
    }
  });
}

/* ------------------------------------------------------------------ */
/* small id helper                                                     */
/* ------------------------------------------------------------------ */

/** Short unique-enough id for locally created records. */
export function newId(prefix) {
  return `${prefix}${Date.now().toString(36)}${Math.floor(Math.random() * 1296)
    .toString(36)
    .padStart(2, '0')}`;
}
